"""Simple listers — the bulk, each just one AWS list/describe call, expressed as plain data.

A simple lister needs no logic: it names the boto3 ``method``, the ``result_path`` to walk, and
the ``id_field`` to pull (plus an optional status filter, and an optional ``cfn_type`` pin for the
boto3-introspected entries at the end). The listers that DO need logic live in
:mod:`.custom_listers`. :mod:`.lister_registry` turns each entry here into a
:class:`~aws_bench.resource_management.fastscan.listers.model.Lister`.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class SimpleLister:
    """One simple lister expressed as data (fields mirror ``runtime.collect``'s arguments)."""

    service: str
    op: str
    method: str
    result_path: str
    id_field: str | None
    status_field: str | None = None
    status_filter: tuple[str, ...] | None = None
    # Need a specific block list because different services have vastly different statuses
    status_exclude: tuple[str, ...] | None = None
    # An exact CFN type pin, set only on the boto3-introspected rows below where the method maps
    # to a single CFN type. Left None on the hand-curated rows (their type is guessed by noun).
    cfn_type: str | None = None


